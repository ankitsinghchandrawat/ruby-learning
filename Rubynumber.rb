# number conversion in Ruby(any data type to integer)
puts Integer(10.89) # Float to integer
puts Integer("10898") # String to integer
puts Integer(0xFF)  # Hexadecimal to integer
puts Integer(0755)  # Octal to integer
puts Integer(0b1010) # Binary to integer
puts "e".getbyte(0)  # Character to integer (ASCII value)

